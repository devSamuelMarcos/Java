public class Switch {
    public static void main(String[] args){
        int num = 5;

        switch (num){
            case 10:
                System.out.println("O valor e 10");
                break;
            case 5:
                System.out.println("O valor e 5");
                break;
            case 2:
                System.out.println("O valor e 2");
                break;
        }
    }
}
